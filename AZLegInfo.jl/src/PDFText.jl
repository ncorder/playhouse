"The text of a glyph name (Adobe Glyph List conventions), or \"\" if unknown."
function glyph_text(name::AbstractString)
    base = split(name, '.')[1]  # /a.sc is a small capital a
    haskey(GLYPH_NAMES, base) && return GLYPH_NAMES[base]
    # /f_f_i is the ligature of f, f and i.
    occursin('_', base) && return join(glyph_text(part) for part in split(base, '_'))
    if length(base) == 1 && isascii(base[1]) && isletter(base[1])
        return String(base)
    end
    m = match(r"^([A-Za-z])([a-z]+)$", base)
    if m !== nothing && haskey(ACCENTS, m.captures[2])
        # A letter and its accent, joined into one character where Unicode has one.
        return Base.Unicode.normalize(m.captures[1] * ACCENTS[m.captures[2]], :NFC)
    end
    m = match(r"^uni((?:[0-9A-F]{4})+)$", base)
    if m !== nothing
        hex = m.captures[1]
        units = UInt16[parse(UInt16, hex[i:i+3], base = 16) for i in 1:4:length(hex)]
        return transcode(String, units)
    end
    m = match(r"^u([0-9A-F]{4,6})$", base)
    if m !== nothing
        c = parse(UInt32, m.captures[1], base = 16)
        return isvalid(Char, c) ? string(Char(c)) : ""
    end
    return ""
end

"Decodes UTF-16BE bytes, the encoding of text in ToUnicode CMaps."
function utf16be(bytes::AbstractVector{UInt8})
    length(bytes) == 1 && return string(Char(bytes[1]))
    units = UInt16[(UInt16(bytes[i]) << 8) | bytes[i+1] for i in 1:2:length(bytes)-1]
    return transcode(String, units)
end

bytes_to_uint(bytes::AbstractVector{UInt8}) = foldl((v, b) -> (v << 8) | b, bytes; init = UInt32(0))

"""
Reads a CMap (section 9.7.5 and 9.10.3): its codespace ranges, the text of
each code (bfchar and bfrange) and the CID of each code (cidchar and cidrange).
"""
function read_cmap(data::Vector{UInt8})
    codespace = Tuple{Int,UInt32,UInt32}[]
    to_unicode = Dict{UInt32,String}()
    to_cid = Dict{UInt32,UInt32}()
    lx = Lexer(data, 1)
    operands = Any[]
    while true
        t = read_object(lx; refs = false)
        t === EOF && break
        if !(t isa Keyword)
            push!(operands, t)
            continue
        end
        empty!(operands)
        section = t.word
        section in ("begincodespacerange", "beginbfchar", "beginbfrange", "begincidchar", "begincidrange") || continue
        stop = Keyword("end" * section[6:end])
        items = Any[]
        while (x = read_object(lx; refs = false)) != stop && x !== EOF
            push!(items, x)
        end
        if section == "begincodespacerange"
            for i in 1:2:length(items)-1
                low, high = items[i], items[i+1]
                (low isa Vector{UInt8} && high isa Vector{UInt8}) || continue
                push!(codespace, (length(low), bytes_to_uint(low), bytes_to_uint(high)))
            end
        elseif section == "beginbfchar"
            for i in 1:2:length(items)-1
                code, text = items[i], items[i+1]
                code isa Vector{UInt8} || continue
                to_unicode[bytes_to_uint(code)] =
                    text isa Vector{UInt8} ? utf16be(text) : text isa Symbol ? glyph_text(string(text)) : ""
            end
        elseif section == "beginbfrange"
            for i in 1:3:length(items)-2
                low, high, text = items[i], items[i+1], items[i+2]
                (low isa Vector{UInt8} && high isa Vector{UInt8}) || continue
                lo, hi = bytes_to_uint(low), bytes_to_uint(high)
                hi - lo > 0xffff && continue  # not a real mapping
                for (k, code) in enumerate(lo:hi)
                    if text isa Vector{UInt8} && !isempty(text)
                        # The last byte counts up from the first code's text.
                        t = copy(text)
                        t[end] += UInt8((code - lo) % 256)
                        to_unicode[code] = utf16be(t)
                    elseif text isa Vector && k <= length(text) && text[k] isa Vector{UInt8}
                        to_unicode[code] = utf16be(text[k])
                    end
                end
            end
        elseif section == "begincidchar"
            for i in 1:2:length(items)-1
                code, cid = items[i], items[i+1]
                (code isa Vector{UInt8} && cid isa Int) && (to_cid[bytes_to_uint(code)] = UInt32(cid))
            end
        else  # begincidrange
            for i in 1:3:length(items)-2
                low, high, cid = items[i], items[i+1], items[i+2]
                (low isa Vector{UInt8} && high isa Vector{UInt8} && cid isa Int) || continue
                lo, hi = bytes_to_uint(low), bytes_to_uint(high)
                hi - lo > 0xffff && continue
                for code in lo:hi
                    to_cid[code] = UInt32(cid + (code - lo))
                end
            end
        end
    end
    return codespace, to_unicode, to_cid
end

"Reads a font dictionary into a Font."
function load_font(doc::Document, font::Dict{Symbol,Any})
    subtype = getvalue(doc, font, :Subtype)
    to_unicode = Dict{UInt32,String}()
    tu = getvalue(doc, font, :ToUnicode)
    if tu isa Stream
        try
            to_unicode = read_cmap(decode(doc, tu))[2]
        catch err
            err isa InterruptException && rethrow()
            @warn "Ignoring a PDF font's ToUnicode CMap, which cannot be read" exception = err
        end
    end
    widths = Dict{UInt32,Float64}()

    if subtype === :Type0
        # A composite font: codes select CIDs through its CMap.
        descendant = resolve(doc, getvalue(doc, font, :DescendantFonts, Any[nothing])[1])
        descendant isa Dict || (descendant = Dict{Symbol,Any}())
        encoding = getvalue(doc, font, :Encoding)
        codespace = Tuple{Int,UInt32,UInt32}[]
        code_to_cid = Dict{UInt32,UInt32}()
        if encoding isa Stream
            try
                codespace, _, code_to_cid = read_cmap(decode(doc, encoding))
            catch err
                err isa InterruptException && rethrow()
                @warn "Reading a PDF font's CMap as Identity-H, as it cannot be read" exception = err
            end
        end
        # /W lists widths as `first [w1 w2 ...]` or `first last w`.
        w = getvalue(doc, descendant, :W, Any[])
        i = 1
        while i < length(w)
            start = resolve(doc, w[i])
            second = resolve(doc, w[i+1])
            start isa Int && start >= 0 || break
            if second isa AbstractVector
                for (k, width) in enumerate(second)
                    widths[UInt32(start + k - 1)] = number(resolve(doc, width)) / 1000
                end
                i += 2
            elseif i + 2 <= length(w) && second isa Int
                width = number(resolve(doc, w[i+2])) / 1000
                for cid in max(start, 0):min(second, 0xffff)  # CIDs are at most 65535
                    widths[UInt32(cid)] = width
                end
                i += 3
            else
                break
            end
        end
        default_width = getvalue(doc, descendant, :DW, 1000) / 1000
        # Vertical writing (section 9.7.4.3): each glyph moves the text down by
        # the second number of /DW2 (glyph-specific /W2 values are not read).
        vertical = encoding === Symbol("Identity-V") ||
                   (encoding isa Stream && getvalue(doc, encoding.dict, :WMode, 0) == 1)
        dw2 = getvalue(doc, descendant, :DW2, Any[880, -1000])
        advance = vertical ? -number(resolve(doc, dw2[end])) / 1000 : 0.0
        return Font(2, codespace, to_unicode, String[], code_to_cid, widths, default_width, advance,
                    Dict{UInt32,String}())
    end

    # A simple font: one byte per code.
    encoding = getvalue(doc, font, :Encoding)
    base = encoding isa Dict ? getvalue(doc, encoding, :BaseEncoding) : encoding
    # Without an encoding, a Type 1 font uses its own, usually StandardEncoding.
    standard = base === :StandardEncoding || (base === nothing && subtype in (:Type1, :MMType1))
    table = copy(standard ? STANDARD : base === :MacRomanEncoding ? MAC_ROMAN : WIN_ANSI)
    if base === nothing && subtype in (:Type1, :MMType1)
        # An embedded Type 1 font program starts with its encoding in plain
        # text, as `dup 65 /A put` (TeX fonts, for example, use their own).
        descriptor = getvalue(doc, font, :FontDescriptor)
        program = descriptor isa Dict ? getvalue(doc, descriptor, :FontFile) : nothing
        if program isa Stream
            data = try
                decode(doc, program)
            catch
                UInt8[]
            end
            r = findfirst(b"eexec", data)
            header = data[1:(r === nothing ? length(data) : first(r) - 1)]
            header = String(map(Char, header))  # read as Latin-1, as it need not be UTF-8
            for m in eachmatch(r"dup\s+(\d+)\s*/([^\s/\[\]]+)\s+put", header)
                code = parse(Int, m.captures[1])
                0 <= code <= 255 && (table[code+1] = glyph_text(m.captures[2]))
            end
        end
    end
    # The glyph names of codes 32 to 126, for the widths of the standard 14 fonts.
    names = Dict{Int,String}(code => STANDARD_14_NAMES[code-31] for code in 32:126)
    if standard
        names[0x27], names[0x60] = "quoteright", "quoteleft"
    end
    if encoding isa Dict
        code = 0
        for item in getvalue(doc, encoding, :Differences, Any[])
            item = resolve(doc, item)
            if item isa Int
                code = item
            elseif item isa Symbol
                if 0 <= code <= 255
                    table[code+1] = glyph_text(string(item))
                    names[code] = string(item)
                end
                code += 1
            end
        end
    end
    # Type 3 glyphs are measured with the font's matrix; others in 1/1000 em.
    scale = 0.001
    if subtype === :Type3
        matrix = getvalue(doc, font, :FontMatrix, Any[0.001])
        scale = number(resolve(doc, matrix[1]))
    end
    firstchar = getvalue(doc, font, :FirstChar, 0)
    for (k, width) in enumerate(getvalue(doc, font, :Widths, Any[]))
        widths[UInt32(firstchar + k - 1)] = number(resolve(doc, width)) * scale
    end
    descriptor = getvalue(doc, font, :FontDescriptor, Dict{Symbol,Any}())
    missing_width = descriptor isa Dict ? getvalue(doc, descriptor, :MissingWidth, 0) : 0
    default_width = missing_width * scale
    if isempty(widths) && subtype !== :Type3
        # A standard 14 font without /Widths; for other fonts, a guess.
        afm = standard_14_widths(getvalue(doc, font, :BaseFont))
        for (code, name) in names
            afm !== nothing && haskey(afm, name) && (widths[UInt32(code)] = afm[name] / 1000)
        end
        default_width = 0.5
    end
    return Font(1, Tuple{Int,UInt32,UInt32}[], to_unicode, table, Dict{UInt32,UInt32}(), widths,
                default_width, 0.0, Dict{UInt32,String}())
end

"Splits the bytes of a string into character codes, each with its length in bytes."
function codes(font::Font, s::Vector{UInt8})
    out = Tuple{UInt32,Int}[]
    i = 1
    n = length(s)
    while i <= n
        len = font.bytes_per_code
        if !isempty(font.codespace)
            # The shortest codespace range that holds the next bytes.
            len = 0
            for k in 1:4
                i + k - 1 > n && break
                v = bytes_to_uint(view(s, i:i+k-1))
                if any(r -> r[1] == k && r[2] <= v <= r[3], font.codespace)
                    len = k
                    break
                end
            end
            len == 0 && (len = min(font.bytes_per_code, n - i + 1))
        end
        len = min(len, n - i + 1)
        push!(out, (bytes_to_uint(view(s, i:i+len-1)), len))
        i += len
    end
    return out
end

"The text of a character code, from the ToUnicode CMap or else the encoding."
function code_text(font::Font, code::UInt32)
    get!(font.texts, code) do
        text = get(font.to_unicode, code, nothing)
        if text === nothing
            text = font.bytes_per_code == 1 && code <= 255 ? font.encoding[code+1] : ""
        end
        clean(text)
    end
end

# Ligature characters, which some fonts map glyphs such as "fi" to, are
# replaced by the letters they join.
const LIGATURES = Dict('ﬀ' => "ff", 'ﬁ' => "fi", 'ﬂ' => "fl", 'ﬃ' => "ffi", 'ﬄ' => "ffl", 'ﬅ' => "st", 'ﬆ' => "st")

"Replaces ligatures, turns tabs and line breaks into spaces and removes other control characters."
function clean(text::String)
    io = IOBuffer()
    for c in text
        if haskey(LIGATURES, c)
            print(io, LIGATURES[c])
        elseif c == '\t' || c == '\n' || c == '\r'
            print(io, ' ')
        elseif !iscntrl(c)
            print(io, c)
        end
    end
    return String(take!(io))
end

function code_width(font::Font, code::UInt32)
    key = font.bytes_per_code == 1 ? code : get(font.code_to_cid, code, code)
    return get(font.widths, key, font.default_width)
end

