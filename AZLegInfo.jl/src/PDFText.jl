# Words and lines
# ---------------------------------------------------------------------------

"A word, or other text without spaces, and where it starts and ends on the page."
struct Word
    text::String
    x::Float64      # left edge, in points from the left of the page
    right::Float64  # right edge (for text that is not horizontal, the x of its last glyph)
end

"A line of text: the baseline's height from the bottom of the page and its words, left to right."
struct Line
    y::Float64
    words::Vector{Word}
end

"The text of a line, with one space between words."
text(line::Line) = join((w.text for w in line.words), " ")

"""
Groups glyphs into lines and words. A glyph is on a line when its baseline is
within 40% of the smaller of its font size and that of the line's first
(highest) glyph, and at least within 0.4 points. A new word starts
after a space, or where the gap after the last glyph is more than 15% of the
font size. A glyph drawn again at almost the same place (to look bold) is
read once. Text that is not horizontal, such as a diagonal watermark or
vertical writing, is not mixed into those lines: each run of it, in the order
it is drawn, is a line of its own.
"""
function lines(glyphs::Vector{Glyph})
    horizontal = filter(g -> g.horizontal, glyphs)
    order = sortperm([g.y for g in horizontal]; rev = true)
    groups = Vector{Vector{Glyph}}()
    for i in order
        g = horizontal[i]
        if isempty(groups) || abs(groups[end][1].y - g.y) > 0.4 * max(min(groups[end][1].size, g.size), 1.0)
            push!(groups, Glyph[])
        end
        push!(groups[end], g)
    end
    out = Line[]
    for group in groups
        sort!(group; by = g -> g.x)
        words = Word[]
        buffer = IOBuffer()
        start = right = -Inf
        kept = Glyph[]
        for g in group
            # Skip a copy of one of the last few glyphs, drawn within 30% of its width and size.
            any(h -> abs(h.x - g.x) < 0.3 * max(h.width, 0.1 * h.size) && abs(h.y - g.y) < 0.3 * h.size &&
                     h.text == g.text, @view kept[max(1, end - 3):end]) && continue
            push!(kept, g)
            # A glyph with no known text ("") keeps its place in the word.
            space = !isempty(g.text) && all(isspace, g.text)
            if space || g.x - right > 0.15 * g.size
                # End the word so far.
                position(buffer) > 0 && push!(words, Word(String(take!(buffer)), start, right))
            end
            if !space && !isempty(g.text)
                position(buffer) == 0 && (start = g.x)
                if occursin(' ', g.text)
                    # Text with a space inside (from a ToUnicode CMap) is two words.
                    for (k, part) in enumerate(split(g.text, ' '))
                        if k > 1 && position(buffer) > 0
                            push!(words, Word(String(take!(buffer)), start, g.x + g.width))
                            start = g.x
                        end
                        print(buffer, part)
                    end
                else
                    print(buffer, g.text)
                end
            end
            right = max(right, g.x + g.width)
        end
        position(buffer) > 0 && push!(words, Word(String(take!(buffer)), start, right))
        isempty(words) || push!(out, Line(group[1].y, words))
    end
    # Runs of glyphs that are not horizontal, placed among the lines by where they start.
    if length(horizontal) < length(glyphs)
        run = Glyph[]
        for (i, g) in enumerate(glyphs)
            g.horizontal || push!(run, g)
            if !isempty(run) && (i == length(glyphs) || glyphs[i+1].horizontal)
                words = run_words(run)
                isempty(words) || push!(out, Line(run[1].y, words))
                run = Glyph[]
            end
        end
        sort!(out; by = line -> line.y, rev = true)
    end
    return out
end

"""
The words of a run of glyphs in the order drawn, in any direction. A new word
starts after a space or where the gap from the end of the last glyph is more
than 15% of the font size. Words are placed at their first and last glyphs.
"""
function run_words(run::Vector{Glyph})
    words = Word[]
    buffer = IOBuffer()
    first = run[1]
    for (k, g) in enumerate(run)
        space = !isempty(g.text) && all(isspace, g.text)
        gap = k == 1 ? 0.0 : hypot(g.x - run[k-1].x, g.y - run[k-1].y) - run[k-1].width
        if (space || gap > 0.15 * g.size) && position(buffer) > 0
            push!(words, Word(String(take!(buffer)), first.x, run[k-1].x))
        end
        position(buffer) == 0 && (first = g)
        space || print(buffer, replace(g.text, ' ' => ""))
    end
    position(buffer) > 0 && push!(words, Word(String(take!(buffer)), first.x, run[end].x))
    return words
end

"""
    read_lines(pdf) -> Vector{Vector{Line}}

Reads the text of every page of a PDF, given as its bytes or as a path to it,
as lines from the top of the page to the bottom, each a list of words from
left to right with their positions, in points from the bottom left corner of
the page's /MediaBox (after the page's /Rotate). Text that is not horizontal,
such as a diagonal watermark, is on lines of its own.
"""
read_lines(path::AbstractString) = read_lines(read(path))

function read_lines(data::Vector{UInt8})
    doc = Document(data)
    fonts = IdDict{Any,Union{Font,Nothing}}()
    return [lines(page_glyphs(doc, page, resources, matrix, fonts)) for (page, resources, matrix) in pages(doc)]
end

