"The AFM widths of a standard 14 font (or a common alias of one, such as Arial), or nothing."
function standard_14_widths(basefont)
    basefont isa Symbol || return nothing
    name = String(basefont)
    occursin('+', name) && (name = split(name, '+'; limit = 2)[2])  # a subset prefix, ABCDEF+
    # Arial,Bold and Arial-BoldMT are both a family and a style.
    family, style = occursin(r"[,-]", name) ? split(name, r"[,-]"; limit = 2) : (name, "")
    family = replace(family, r"(PSMT|MT|PS)$" => "")  # ArialMT, TimesNewRomanPSMT
    bold = occursin("Bold", style)
    italic = occursin("Italic", style) || occursin("Oblique", style)
    if family in ("Helvetica", "Arial")
        return STANDARD_14_WIDTHS[bold ? "Helvetica-Bold" : "Helvetica"]
    elseif family in ("Times", "TimesNewRoman")
        return STANDARD_14_WIDTHS[bold && italic ? "Times-BoldItalic" : bold ? "Times-Bold" :
                                  italic ? "Times-Italic" : "Times-Roman"]
    elseif family in ("Courier", "CourierNew")
        return Dict(n => 600 for n in STANDARD_14_NAMES)
    end
    return nothing
end

