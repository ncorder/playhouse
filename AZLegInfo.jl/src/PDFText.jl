"""
A PDF file in memory. `xref` maps an object number to where the object is:
`(1, offset, generation)` for an object in the file, or `(2, stream, index)`
for an object inside the object stream with object number `stream`.
"""
mutable struct Document
    data::Vector{UInt8}
    xref::Dict{Int,NTuple{3,Int}}
    trailer::Dict{Symbol,Any}
    objects::Dict{Int,Any}
    object_streams::Dict{Int,Dict{Int,Any}}
    loading::Set{Int}  # objects being read, to stop reference cycles
    scanned::Union{Nothing,Dict{Int,NTuple{2,Int}}}  # scan_objects, once it has been needed
    quiet::Bool  # no warnings about damaged objects while the xref is checked or rebuilt
end

function Document(data::Vector{UInt8})
    doc = Document(data, Dict{Int,NTuple{3,Int}}(), Dict{Symbol,Any}(),
                   Dict{Int,Any}(), Dict{Int,Dict{Int,Any}}(), Set{Int}(), nothing, true)
    try
        read_cross_references!(doc)
        haskey(doc.trailer, :Root) || error("no /Root in the trailer")
        # A wrong offset usually shows up here, as the catalog not being found.
        resolve(doc, doc.trailer[:Root]) isa Dict || error("the /Root is not a dictionary")
    catch err
        # The cross-reference data is damaged, so the objects are found by
        # scanning the whole file, as PDF readers commonly do.
        err isa InterruptException && rethrow()
        rebuild_cross_references!(doc)
    finally
        doc.quiet = false
    end
    haskey(doc.trailer, :Encrypt) && error("Encrypted PDFs are not supported")
    return doc
end

"Follows a Ref to the object it points to; any other object is returned as is."
resolve(doc::Document, x) = x isa Ref ? get_object(doc, x.num) : x

"Looks up `key` in `dict`, following a Ref, and returns `default` if it is missing."
getvalue(doc::Document, dict::AbstractDict, key::Symbol, default = nothing) =
    something(resolve(doc, get(dict, key, nothing)), Some(default))

"""
The object with number `num`, or `nothing` if there is none. An object that
cannot be read (because the file is damaged) is also read as `nothing`, with a
warning, as other PDF readers do.
"""
function get_object(doc::Document, num::Int)
    haskey(doc.objects, num) && return doc.objects[num]
    entry = get(doc.xref, num, nothing)
    entry === nothing && return nothing
    num in doc.loading && error("PDF object $num refers to itself")
    push!(doc.loading, num)
    object = try
        if entry[1] == 1
            try
                read_indirect_object(doc, entry[2], num)
            catch err
                err isa InterruptException && rethrow()
                # A wrong offset in the xref: look for the object in the file.
                doc.scanned === nothing && (doc.scanned = scan_objects(doc.data))
                found = get(doc.scanned, num, nothing)
                (found === nothing || found[1] == entry[2]) && rethrow()
                read_indirect_object(doc, found[1], num)
            end
        else
            get(object_stream(doc, entry[2]), num, nothing)
        end
    catch err
        err isa InterruptException && rethrow()
        doc.quiet || @warn "Skipping PDF object $num, which cannot be read" exception = err
        nothing
    finally
        delete!(doc.loading, num)
    end
    doc.objects[num] = object
    return object
end

"Reads `num gen obj ... endobj` at the 0-based byte `offset`."
function read_indirect_object(doc::Document, offset::Int, num::Int)
    lx = Lexer(doc.data, offset + 1)
    found = read_token(lx)
    read_token(lx)
    read_token(lx) == Keyword("obj") || error("No object at byte $offset")
    found == num || error("Object $num is not at byte $offset")
    object = read_object(lx)
    if object isa Dict && read_token(lx) == Keyword("stream")
        return read_stream_data(doc, lx, object)
    end
    return object
end

"Reads the bytes after the keyword `stream`, which `lx` has just read."
function read_stream_data(doc::Document, lx::Lexer, dict::Dict{Symbol,Any})
    d, n = doc.data, length(doc.data)
    p = lx.pos
    # The keyword is followed by CRLF or LF (or, in some files, CR alone).
    p <= n && d[p] == 0x0d && (p += 1)
    p <= n && d[p] == 0x0a && (p += 1)
    len = try
        resolve(doc, get(dict, :Length, nothing))
    catch
        nothing
    end
    if len isa Integer && 0 <= len <= n - p + 1 && ends_stream(d, p + len)
        return Stream(dict, d[p:p+len-1])
    end
    # A wrong /Length: the data ends at the keyword `endstream`.
    r = findnext(b"endstream", d, p)
    r === nothing && error("A PDF stream has no end")
    q = first(r) - 1
    q >= p && d[q] == 0x0a && (q -= 1)
    q >= p && d[q] == 0x0d && (q -= 1)
    return Stream(dict, d[p:q])
end

"Whether `endstream` follows byte `p` (after an optional end of line)."
function ends_stream(d::Vector{UInt8}, p::Int)
    while p <= length(d) && iswhite(d[p])
        p += 1
    end
    return p + 8 <= length(d) && view(d, p:p+8) == b"endstream"
end

"""
The objects inside the object stream `num` (section 7.5.7), by object number.
A damaged object stream is read as empty, with a warning.
"""
function object_stream(doc::Document, num::Int)
    get!(doc.object_streams, num) do
        try
            read_object_stream(doc, num)
        catch err
            err isa InterruptException && rethrow()
            doc.quiet || @warn "Skipping PDF object stream $num, which cannot be read" exception = err
            Dict{Int,Any}()
        end
    end
end

function read_object_stream(doc::Document, num::Int)
    stream = get_object(doc, num)
    stream isa Stream || error("PDF object $num is not an object stream")
    data = decode(doc, stream)
    # Each object needs at least 4 bytes ("1 0 " in the header), which bounds /N.
    count = clamp(getvalue(doc, stream.dict, :N, 0), 0, length(data) ÷ 4)
    start = getvalue(doc, stream.dict, :First, 0)
    lx = Lexer(data, 1)
    header = Tuple{Int,Int}[]
    for _ in 1:count
        objnum, offset = read_token(lx), read_token(lx)
        (objnum isa Int && offset isa Int) || break  # a damaged header or /N
        push!(header, (objnum, offset))
    end
    objects = Dict{Int,Any}()
    for (objnum, offset) in header
        lx.pos = start + offset + 1
        objects[objnum] = read_object(lx)
    end
    return objects
end

"Finds the byte offset after the last `startxref` in the file."
function find_startxref(d::Vector{UInt8})
    r = findprev(b"startxref", d, length(d))
    r === nothing && error("No startxref")
    offset = read_token(Lexer(d, last(r) + 1))
    offset isa Int || error("No offset after startxref")
    return offset
end

"""
Reads every cross-reference section, newest first, following /Prev. Entries
from newer sections win; free entries are skipped, so an object listed as free
in the table of a hybrid file is still found in its /XRefStm stream.
"""
function read_cross_references!(doc::Document)
    offset = find_startxref(doc.data)
    seen = Set{Int}()
    while offset !== nothing && !(offset in seen)
        push!(seen, offset)
        lx = Lexer(doc.data, offset + 1)
        trailer = if read_token(lx) == Keyword("xref")
            t = read_xref_table!(doc, lx)
            # Hybrid files list the objects in object streams in a stream.
            hybrid = get(t, :XRefStm, nothing)
            hybrid isa Int && !(hybrid in seen) && (push!(seen, hybrid); read_xref_stream!(doc, hybrid))
            t
        else
            read_xref_stream!(doc, offset)
        end
        for (key, value) in trailer
            haskey(doc.trailer, key) || (doc.trailer[key] = value)
        end
        prev = get(trailer, :Prev, nothing)
        offset = prev isa Integer ? Int(prev) : nothing
    end
    return doc
end

"Reads a classic `xref` table (section 7.5.4) and returns its trailer dictionary."
function read_xref_table!(doc::Document, lx::Lexer)
    while true
        start = read_token(lx)
        start == Keyword("trailer") && break
        count = read_token(lx)
        # Each entry takes 20 bytes (19 in some damaged files; 18 leaves slack),
        # which bounds a subsection's count.
        (start isa Int && count isa Int && 0 <= count <= (length(doc.data) - lx.pos) ÷ 18) ||
            error("Damaged xref table")
        for num in start:start+count-1
            offset, gen, kind = read_token(lx), read_token(lx), read_token(lx)
            (offset isa Int && gen isa Int && (kind == Keyword("n") || kind == Keyword("f"))) ||
                error("Damaged xref table")
            if kind == Keyword("n") && offset > 0
                haskey(doc.xref, num) || (doc.xref[num] = (1, offset, gen))
            end
        end
    end
    trailer = read_object(lx)
    trailer isa Dict || error("Damaged trailer")
    return trailer
end

"Reads a cross-reference stream (section 7.5.8) and returns its dictionary."
function read_xref_stream!(doc::Document, offset::Int)
    lx = Lexer(doc.data, offset + 1)
    read_token(lx)
    read_token(lx)
    read_token(lx) == Keyword("obj") || error("No xref stream at byte $offset")
    dict = read_object(lx)
    (dict isa Dict && read_token(lx) == Keyword("stream")) || error("No xref stream at byte $offset")
    stream = read_stream_data(doc, lx, dict)
    data = decode(doc, stream)
    widths = Int[resolve(doc, w) for w in dict[:W]]
    # Every entry must use some bytes, or a huge /Size would loop without end.
    (length(widths) == 3 && all(>=(0), widths) && sum(widths) > 0) || error("Damaged xref stream")
    size = get(dict, :Size, 0)
    index = get(dict, :Index, Any[0, size])
    p = 1
    field(w, default) = w == 0 ? default : (v = 0; for _ in 1:w; v = 256v + data[p]; p += 1; end; v)
    for k in 1:2:length(index)-1
        for num in index[k]:index[k]+index[k+1]-1
            p + sum(widths) - 1 <= length(data) || break
            kind = field(widths[1], 1)
            a = field(widths[2], 0)
            b = field(widths[3], 0)
            if kind == 1 || kind == 2
                haskey(doc.xref, num) || (doc.xref[num] = (kind, a, b))
            end
        end
    end
    return dict
end

"""
Finds every `num gen obj` in the file, as a Dict from object number to its
0-based offset and generation. A later definition of an object wins, as it
would in an incremental update.
"""
function scan_objects(d::Vector{UInt8})
    found = Dict{Int,NTuple{2,Int}}()
    r = findnext(b"obj", d, 1)
    while r !== nothing
        p = first(r)
        # "obj" must be a whole word, after "num gen ".
        if (p + 3 > length(d) || !isregular(d[p+3])) && p > 1 && iswhite(d[p-1])
            q = p - 1
            while q >= 1 && iswhite(d[q]); q -= 1; end
            gen_end = q
            while q >= 1 && isdigit_byte(d[q]); q -= 1; end
            gen_start = q + 1
            while q >= 1 && iswhite(d[q]); q -= 1; end
            num_end = q
            while q >= 1 && isdigit_byte(d[q]); q -= 1; end
            num_start = q + 1
            if gen_start <= gen_end && num_start <= num_end && num_end < gen_start - 1 &&
               num_end - num_start < 18 && gen_end - gen_start < 18 && (q < 1 || !isregular(d[q]))
                num = parse(Int, String(d[num_start:num_end]))
                found[num] = (num_start - 1, parse(Int, String(d[gen_start:gen_end])))
            end
        end
        r = findnext(b"obj", d, p + 3)
    end
    return found
end

"""
Rebuilds the cross-reference data by scanning the file for objects, for files
whose cross-reference data is damaged.
"""
function rebuild_cross_references!(doc::Document)
    d = doc.data
    empty!(doc.xref)
    empty!(doc.objects)
    empty!(doc.object_streams)
    empty!(doc.trailer)
    doc.scanned = scan_objects(d)
    for (num, (offset, gen)) in doc.scanned
        doc.xref[num] = (1, offset, gen)
    end
    # Objects in object streams, and the trailer.
    for num in sort!(collect(keys(doc.xref)))
        object = get_object(doc, num)  # nothing if it cannot be read
        if object isa Stream
            type = get(object.dict, :Type, nothing)
            if type === :ObjStm
                inner_objects = object_stream(doc, num)
                isempty(inner_objects) && @warn "PDF object stream $num cannot be read; the objects in it are missing"
                for inner in keys(inner_objects)
                    haskey(doc.xref, inner) || (doc.xref[inner] = (2, num, 0))
                end
            elseif type === :XRef
                merge!(doc.trailer, object.dict)
            end
        elseif object isa Dict && get(object, :Type, nothing) === :Catalog
            doc.trailer[:Root] = Ref(num, 0)
        end
    end
    r = findprev(b"trailer", d, length(d))
    while r !== nothing
        t = try
            read_object(Lexer(d, last(r) + 1))
        catch
            nothing
        end
        if t isa Dict && haskey(t, :Root)
            merge!(doc.trailer, t)
            break
        end
        r = findprev(b"trailer", d, first(r) - 1)
    end
    # Objects that failed while the xref was incomplete are read again when needed.
    empty!(doc.objects)
    haskey(doc.trailer, :Root) || error("Not a readable PDF: no document catalog")
    return doc
end

