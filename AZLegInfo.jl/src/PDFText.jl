"Returns the decoded bytes of a stream."
function decode(doc::Document, stream::Stream)
    filters = getvalue(doc, stream.dict, :Filter)
    params = getvalue(doc, stream.dict, :DecodeParms)
    filters === nothing && return stream.data
    if filters isa Symbol
        filters = Any[filters]
        params = Any[params]
    elseif !(params isa AbstractVector)
        params = fill(params, length(filters))
    end
    data = stream.data
    for (filter, param) in zip(filters, params)
        filter = resolve(doc, filter)
        param = resolve(doc, param)
        if filter === :FlateDecode || filter === :Fl
            data = flate_decode(data)
            param isa Dict && (data = unpredict(doc, data, param))
        elseif filter === :LZWDecode || filter === :LZW
            early = param isa Dict ? getvalue(doc, param, :EarlyChange, 1) : 1
            data = lzw_decode(data, early)
            param isa Dict && (data = unpredict(doc, data, param))
        elseif filter === :ASCIIHexDecode || filter === :AHx
            data = read_hex_string!(Lexer(vcat(UInt8('<'), data), 1))
        elseif filter === :ASCII85Decode || filter === :A85
            data = ascii85_decode(data)
        elseif filter === :RunLengthDecode || filter === :RL
            data = run_length_decode(data)
        else
            error("Unsupported PDF stream filter: $filter")
        end
    end
    return data
end

"""
Decompresses zlib data. Like other PDF readers, it accepts data whose Adler-32
checksum at the end is wrong or missing, by reading the Deflate data inside,
but warns, as the data may also be damaged.
"""
function flate_decode(data::Vector{UInt8})
    try
        return inflate_zlib(data)
    catch err
        (err isa InterruptException || length(data) <= 2) && rethrow()
        out = inflate(data[3:end])  # after the 2-byte zlib header
        @warn "A PDF stream's checksum is wrong or missing, so its text may be damaged"
        return out
    end
end

"Decodes ASCII85 (section 7.4.3): groups of 5 characters from ! to u for 4 bytes, z for 4 zeros."
function ascii85_decode(data::Vector{UInt8})
    out = UInt8[]
    group = UInt64(0)
    k = 0
    for b in data
        b == UInt8('~') && break  # the end marker ~>
        iswhite(b) && continue
        if b == UInt8('z') && k == 0
            append!(out, (0x00, 0x00, 0x00, 0x00))
            continue
        end
        UInt8('!') <= b <= UInt8('u') || error("Damaged ASCII85 data")
        group = 85 * group + (b - UInt8('!'))
        k += 1
        if k == 5
            group > 0xffffffff && error("Damaged ASCII85 data")
            append!(out, reinterpret(UInt8, [hton(UInt32(group))]))
            group, k = UInt64(0), 0
        end
    end
    if k > 1
        # A last group of k characters is padded with u and gives k - 1 bytes.
        for _ in k+1:5
            group = 85 * group + 84
        end
        append!(out, reinterpret(UInt8, [hton(UInt32(group & 0xffffffff))])[1:k-1])
    end
    return out
end

"Decodes RunLength data (section 7.4.5)."
function run_length_decode(data::Vector{UInt8})
    out = UInt8[]
    p = 1
    while p <= length(data)
        n = data[p]
        p += 1
        n == 128 && break  # end of data
        if n < 128
            # The next n + 1 bytes are copied.
            append!(out, view(data, p:min(p + n, length(data))))
            p += n + 1
        elseif p <= length(data)
            # The next byte is repeated 257 - n times.
            append!(out, fill(data[p], 257 - n))
            p += 1
        end
    end
    return out
end

"Decodes LZW data (section 7.4.4), with codes of 9 to 12 bits."
function lzw_decode(data::Vector{UInt8}, early::Integer = 1)
    out = UInt8[]
    table = [[UInt8(i)] for i in 0:255]
    push!(table, UInt8[], UInt8[])  # 256 clears the table, 257 ends the data
    bits = 9
    buffer = 0
    nbits = 0
    previous = UInt8[]
    for b in data
        buffer = ((buffer << 8) | b) & 0xffffff
        nbits += 8
        while nbits >= bits
            code = (buffer >> (nbits - bits)) & ((1 << bits) - 1)
            nbits -= bits
            if code == 256
                resize!(table, 258)
                bits = 9
                previous = UInt8[]
                continue
            end
            code == 257 && return out
            if code < length(table)
                entry = table[code+1]
            elseif !isempty(previous) && code == length(table)
                entry = vcat(previous, previous[1])
            else
                error("Damaged LZW data")
            end
            append!(out, entry)
            isempty(previous) || length(table) < 4096 && push!(table, vcat(previous, entry[1]))
            previous = entry
            # The code length grows one code early when EarlyChange is 1.
            bits = min(12, length(table) + early >= (1 << bits) ? bits + 1 : bits)
        end
    end
    return out
end

"Undoes a TIFF (2) or PNG (10 to 15) predictor, which xref streams often use."
function unpredict(doc::Document, data::Vector{UInt8}, param::Dict{Symbol,Any})
    predictor = getvalue(doc, param, :Predictor, 1)
    predictor == 1 && return data
    colors = getvalue(doc, param, :Colors, 1)
    bits = getvalue(doc, param, :BitsPerComponent, 8)
    columns = getvalue(doc, param, :Columns, 1)
    bpp = max(1, (colors * bits) ÷ 8)          # bytes per pixel
    rowlength = (colors * bits * columns + 7) ÷ 8
    if predictor == 2
        bits == 8 || error("Unsupported TIFF predictor with $bits bits per component")
        out = copy(data)
        for row in 0:(length(out) ÷ rowlength)-1, i in bpp+1:rowlength
            k = row * rowlength + i
            out[k] += out[k-bpp]
        end
        return out
    end
    out = UInt8[]
    previous = zeros(UInt8, rowlength)
    current = zeros(UInt8, rowlength)
    p = 1
    while p + rowlength <= length(data)
        type = data[p]
        for i in 1:rowlength
            raw = data[p+i]
            left = i > bpp ? current[i-bpp] : 0x00
            up = previous[i]
            upleft = i > bpp ? previous[i-bpp] : 0x00
            current[i] = if type == 0
                raw
            elseif type == 1
                raw + left
            elseif type == 2
                raw + up
            elseif type == 3
                raw + UInt8((Int(left) + Int(up)) ÷ 2)
            elseif type == 4
                raw + paeth(left, up, upleft)
            else
                error("Unknown PNG predictor type $type")
            end
        end
        append!(out, current)
        previous, current = current, previous
        p += rowlength + 1
    end
    return out
end

function paeth(a::UInt8, b::UInt8, c::UInt8)
    p = Int(a) + Int(b) - Int(c)
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return pa <= pb && pa <= pc ? a : pb <= pc ? b : c
end

