"""
    PDFText

Reads the text of a PDF, and where each word is on the page, in pure Julia.

It implements the parts of the PDF specification (ISO 32000-1) needed to find
the text of a page:

- the file structure: cross-reference tables and streams, object streams and
  incremental updates, and rebuilding the cross-reference data by scanning the
  file when it is damaged;
- the stream filters FlateDecode (decompressed by the pure-Julia Inflate
  package), LZWDecode, ASCIIHexDecode, ASCII85Decode and RunLengthDecode;
- fonts: simple fonts with WinAnsi, MacRoman or Standard encodings,
  /Differences, the encodings built into Type 1 fonts, and the widths of the
  standard Helvetica, Times and Courier fonts; composite (Type0) fonts with
  Identity or embedded CMaps, including vertical ones; ToUnicode CMaps and
  glyph widths;
- the text operators of content streams, including text inside form XObjects,
  on pages that are rotated or whose /MediaBox does not start at 0, 0.

It does not render anything, decrypt encrypted PDFs, or read text that exists
only in images (scans). Damaged parts of a file are skipped with a warning.

Citations:
  Code generated by Claude Code, Anthropic, September 24, 2026, https://claude.ai/code/session_019awDnsGJAcXbzPNQg6VhqU.
"""
module PDFText

using Inflate

# ---------------------------------------------------------------------------
# PDF objects
#
# null is `nothing`, booleans are Bool, numbers are Int or Float64, names are
# Symbols, strings are Vector{UInt8} (their bytes; what they mean depends on
# the font), arrays are Vector{Any} and dictionaries are Dict{Symbol,Any}.
# ---------------------------------------------------------------------------

"A reference to the indirect object `num gen obj` (written `num gen R`)."
struct Ref
    num::Int
    gen::Int
end

"A stream object: its dictionary and its still-encoded bytes."
struct Stream
    dict::Dict{Symbol,Any}
    data::Vector{UInt8}
end

"A bare word such as `obj`, `R`, `true` or a content stream operator like `Tj`."
struct Keyword
    word::String
end

const EOF = Keyword("")
const ARRAY_START = Keyword("[")
const ARRAY_END = Keyword("]")
const DICT_START = Keyword("<<")
const DICT_END = Keyword(">>")

# ---------------------------------------------------------------------------
# Lexer (PDF 32000-1:2008, section 7.2 and 7.3)
# ---------------------------------------------------------------------------

mutable struct Lexer
    data::Vector{UInt8}
    pos::Int  # index of the next byte to read
end

iswhite(b::UInt8) = b == 0x20 || b == 0x0a || b == 0x0d || b == 0x09 || b == 0x0c || b == 0x00
isdelimiter(b::UInt8) = b == UInt8('(') || b == UInt8(')') || b == UInt8('<') || b == UInt8('>') ||
                        b == UInt8('[') || b == UInt8(']') || b == UInt8('{') || b == UInt8('}') ||
                        b == UInt8('/') || b == UInt8('%')
isregular(b::UInt8) = !iswhite(b) && !isdelimiter(b)
isdigit_byte(b::UInt8) = UInt8('0') <= b <= UInt8('9')

function hexvalue(b::UInt8)
    UInt8('0') <= b <= UInt8('9') && return Int(b - UInt8('0'))
    UInt8('a') <= b <= UInt8('f') && return Int(b - UInt8('a')) + 10
    UInt8('A') <= b <= UInt8('F') && return Int(b - UInt8('A')) + 10
    return -1
end

"Skips whitespace and comments."
function skip_space!(lx::Lexer)
    d, p, n = lx.data, lx.pos, length(lx.data)
    while p <= n
        b = d[p]
        if iswhite(b)
            p += 1
        elseif b == UInt8('%')
            while p <= n && d[p] != 0x0a && d[p] != 0x0d
                p += 1
            end
        else
            break
        end
    end
    lx.pos = p
    return lx
end

"Reads one token: a number, name, string, keyword, or one of `[ ] << >>`."
function read_token(lx::Lexer)
    skip_space!(lx)
    d, p, n = lx.data, lx.pos, length(lx.data)
    p > n && return EOF
    b = d[p]
    if b == UInt8('/')
        q = p + 1
        name = UInt8[]
        while q <= n && isregular(d[q])
            # #xx is the byte with hexadecimal code xx
            if d[q] == UInt8('#') && q + 2 <= n && hexvalue(d[q+1]) >= 0 && hexvalue(d[q+2]) >= 0
                push!(name, UInt8(16 * hexvalue(d[q+1]) + hexvalue(d[q+2])))
                q += 3
            else
                push!(name, d[q])
                q += 1
            end
        end
        lx.pos = q
        return Symbol(String(name))
    elseif b == UInt8('(')
        return read_literal_string!(lx)
    elseif b == UInt8('<')
        if p < n && d[p+1] == UInt8('<')
            lx.pos = p + 2
            return DICT_START
        end
        return read_hex_string!(lx)
    elseif b == UInt8('>') && p < n && d[p+1] == UInt8('>')
        lx.pos = p + 2
        return DICT_END
    elseif b == UInt8('[')
        lx.pos = p + 1
        return ARRAY_START
    elseif b == UInt8(']')
        lx.pos = p + 1
        return ARRAY_END
    elseif isdelimiter(b)
        # A stray ")", ">", "{" or "}"; "{" and "}" only appear in PostScript
        # functions, which are not needed to read text.
        lx.pos = p + 1
        return Keyword(String([b]))
    end
    q = p
    while q <= n && isregular(d[q])
        q += 1
    end
    lx.pos = q
    return number_or_keyword(d, p, q - 1)
end

"Parses `d[p:q]` as an integer or real number, or else returns it as a Keyword."
function number_or_keyword(d::Vector{UInt8}, p::Int, q::Int)
    i = p
    negative = false
    if d[i] == UInt8('-') || d[i] == UInt8('+')
        negative = d[i] == UInt8('-')
        i += 1
    end
    whole = 0
    fraction = 0.0
    scale = 1.0
    digits = 0  # before the point
    point = false
    while i <= q
        b = d[i]
        if isdigit_byte(b)
            if point
                scale /= 10
                fraction += (b - UInt8('0')) * scale
            else
                whole = 10 * whole + (b - UInt8('0'))
                digits += 1
            end
        elseif b == UInt8('.') && !point
            point = true
        else
            return keyword(d, p, q)
        end
        i += 1
    end
    (digits > 0 || scale < 1) || return keyword(d, p, q)
    # More than 18 digits could overflow an Int; such numbers are read as reals.
    digits > 18 && return parse(Float64, String(d[p:q]))
    point || return negative ? -whole : whole
    value = whole + fraction
    return negative ? -value : value
end

# Keywords of up to 4 bytes, packed into a UInt32. They include every content
# stream operator, so reading an operator does not allocate a new String.
pack(bytes) = foldl((key, b) -> (key << 8) | UInt8(b), bytes; init = UInt32(0))

const KEYWORDS = Dict(pack(codeunits(w)) => Keyword(w) for w in split(
    "obj R n f true null b B b* B* BDC BI BMC BT BX c cm CS cs d d0 d1 Do DP EI EMC ET EX q Q " *
    "f* F G g gs h i ID j J K k l m M MP re RG rg ri s S SC sc SCN scn sh T* Tc Td TD Tf Tj TJ " *
    "TL Tm Tr Ts Tw Tz v w W W* y ' \""))

function keyword(d::Vector{UInt8}, p::Int, q::Int)
    if q - p < 4
        k = get(KEYWORDS, pack(view(d, p:q)), nothing)
        k === nothing || return k
    end
    return Keyword(String(d[p:q]))
end

"Reads a `(literal string)`, starting at its opening parenthesis."
function read_literal_string!(lx::Lexer)
    d, n = lx.data, length(lx.data)
    p = lx.pos + 1
    out = UInt8[]
    depth = 1
    while p <= n
        b = d[p]
        if b == UInt8('\\')
            p += 1
            p > n && break
            c = d[p]
            if c == UInt8('n')
                push!(out, 0x0a)
            elseif c == UInt8('r')
                push!(out, 0x0d)
            elseif c == UInt8('t')
                push!(out, 0x09)
            elseif c == UInt8('b')
                push!(out, 0x08)
            elseif c == UInt8('f')
                push!(out, 0x0c)
            elseif UInt8('0') <= c <= UInt8('7')
                # Up to three octal digits; overflow past one byte is ignored.
                value = 0
                k = 0
                while k < 3 && p <= n && UInt8('0') <= d[p] <= UInt8('7')
                    value = 8 * value + (d[p] - UInt8('0'))
                    p += 1
                    k += 1
                end
                push!(out, value % UInt8)
                continue
            elseif c == 0x0d
                # A backslash at the end of a line continues the string.
                p < n && d[p+1] == 0x0a && (p += 1)
            elseif c != 0x0a
                push!(out, c)  # \( \) \\ and unknown escapes are the character itself
            end
            p += 1
        elseif b == UInt8('(')
            depth += 1
            push!(out, b)
            p += 1
        elseif b == UInt8(')')
            depth -= 1
            p += 1
            depth == 0 && break
            push!(out, b)
        elseif b == 0x0d
            # An end of line (CR, LF or CRLF) inside a string is read as LF.
            push!(out, 0x0a)
            p += 1
            p <= n && d[p] == 0x0a && (p += 1)
        else
            push!(out, b)
            p += 1
        end
    end
    lx.pos = p
    return out
end

"Reads a `<hexadecimal string>`, starting at its `<`."
function read_hex_string!(lx::Lexer)
    d, n = lx.data, length(lx.data)
    p = lx.pos + 1
    out = UInt8[]
    high = -1
    while p <= n
        b = d[p]
        p += 1
        b == UInt8('>') && break
        v = hexvalue(b)
        v < 0 && continue  # whitespace
        if high < 0
            high = v
        else
            push!(out, UInt8(16 * high + v))
            high = -1
        end
    end
    high >= 0 && push!(out, UInt8(16 * high))  # a missing last digit is 0
    lx.pos = p
    return out
end

"""
Reads one object. In a file (`refs = true`) `num gen R` is read as a Ref;
content streams have no references, so there it would be three operands.
"""
read_object(lx::Lexer; refs::Bool = true) = finish_object(lx, read_token(lx), refs)

# Real PDFs nest arrays and dictionaries a few levels deep; a limit keeps a
# damaged file (such as 10 KB of "[") from overflowing the stack.
const MAX_NESTING = 100

function finish_object(lx::Lexer, token, refs::Bool, depth::Int = 0)
    if (token === ARRAY_START || token === DICT_START) && depth >= MAX_NESTING
        error("PDF arrays or dictionaries nested more than $MAX_NESTING deep")
    end
    if token === ARRAY_START
        items = Any[]
        while true
            t = read_token(lx)
            (t === ARRAY_END || t === EOF) && break
            # Integers are pushed as they are and joined into references
            # below, so an array of numbers is not read ahead three times.
            push!(items, t isa Int ? t : finish_object(lx, t, refs, depth + 1))
        end
        return refs ? join_references(items) : items
    elseif token === DICT_START
        dict = Dict{Symbol,Any}()
        while true
            key = read_token(lx)
            (key === DICT_END || key === EOF) && break
            key isa Symbol || continue  # skip anything malformed
            value = read_token(lx)
            (value === DICT_END || value === EOF) && break
            dict[key] = finish_object(lx, value, refs, depth + 1)
        end
        return dict
    elseif token isa Keyword
        token.word == "true" && return true
        token.word == "false" && return false
        token.word == "null" && return nothing
        return token
    elseif refs && token isa Int
        # `num gen R` is a reference.
        start = lx.pos
        gen = read_token(lx)
        if gen isa Int && read_token(lx) == Keyword("R")
            return Ref(token, gen)
        end
        lx.pos = start
    end
    return token
end

function join_references(items::Vector{Any})
    out = Any[]
    i = 1
    while i <= length(items)
        if i + 2 <= length(items) && items[i] isa Int && items[i+1] isa Int && items[i+2] == Keyword("R")
            push!(out, Ref(items[i], items[i+1]))
            i += 3
        else
            push!(out, items[i])
            i += 1
        end
    end
    return out
end

